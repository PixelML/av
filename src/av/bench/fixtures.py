"""Deterministic synthetic fixtures for the temporal-ordering capability gate.

Every fixture is generated by a pinned ffmpeg invocation from a solid-colour
``lavfi`` source and font-free ``drawbox`` overlays, so it reproduces byte-for-byte
on any machine with the same ffmpeg build. No fonts, no random seeds, no assets.

Three ordered properties, all trivially checkable:

``color``   frame *k* is a named solid colour from a fixed palette
``count``   frame *k* carries exactly *k* white squares on black
``motion``  a single white square advances left to right, one step per frame
"""

from __future__ import annotations

import subprocess
from dataclasses import dataclass
from pathlib import Path

from av.core.exceptions import FFmpegError

FIXTURE_SIZE = 512
FIXTURE_VERSION = 1

# Ordered, unambiguously nameable colours. Order is part of the contract:
# changing it changes every colour fixture, so append only.
COLOR_PALETTE: list[tuple[str, str]] = [
    ("red", "0xFF0000"),
    ("green", "0x00A000"),
    ("blue", "0x0000FF"),
    ("yellow", "0xFFFF00"),
    ("magenta", "0xFF00FF"),
    ("cyan", "0x00FFFF"),
    ("white", "0xFFFFFF"),
    ("orange", "0xFF8000"),
    ("purple", "0x8000FF"),
    ("pink", "0xFF80C0"),
    ("brown", "0x804000"),
    ("gray", "0x808080"),
]

FIXTURE_KINDS = ("color", "count", "motion")

# Practical ceilings. `color` is limited by how many colours a person (or a model)
# can name without ambiguity; the others by how many marks fit legibly in a frame.
MAX_N = {"color": len(COLOR_PALETTE), "count": 32, "motion": 32}


@dataclass
class Fixture:
    kind: str
    n: int
    frame_paths: list[Path]
    labels: list[str]
    ffmpeg_commands: list[str]

    @property
    def expected_answer(self) -> list[str]:
        return list(self.labels)


def _run_ffmpeg(cmd: list[str]) -> None:
    try:
        subprocess.run(cmd, capture_output=True, text=True, check=True, timeout=60)
    except FileNotFoundError:
        raise FFmpegError("ffmpeg not found. Install ffmpeg: brew install ffmpeg", cmd=" ".join(cmd))
    except subprocess.CalledProcessError as e:
        raise FFmpegError(
            f"Fixture generation failed: {e.stderr}", cmd=" ".join(cmd), returncode=e.returncode
        )
    except subprocess.TimeoutExpired:
        raise FFmpegError("Fixture generation timed out", cmd=" ".join(cmd))


def _base_cmd(source: str, out_path: Path, vf: str | None = None) -> list[str]:
    cmd = [
        "ffmpeg", "-hide_banner", "-loglevel", "error", "-nostdin", "-y",
        "-f", "lavfi", "-i", source,
    ]
    if vf:
        cmd += ["-vf", vf]
    cmd += ["-frames:v", "1", "-q:v", "2", str(out_path)]
    return cmd


def _count_boxes(k: int) -> str:
    """`k` white squares on a fixed 6-column grid, filled in reading order."""
    box, gap, margin = 48, 16, 40
    parts = []
    for i in range(k):
        col, row = i % 6, i // 6
        x = margin + col * (box + gap)
        y = margin + row * (box + gap)
        parts.append(f"drawbox=x={x}:y={y}:w={box}:h={box}:color=white:t=fill")
    return ",".join(parts)


def _motion_box(k: int, n: int) -> str:
    """One white square whose x position is a fixed function of frame index."""
    box = 64
    span = FIXTURE_SIZE - box - 2 * 32
    x = 32 + (span * k // max(n - 1, 1))
    y = (FIXTURE_SIZE - box) // 2
    return f"drawbox=x={x}:y={y}:w={box}:h={box}:color=white:t=fill"


def generate_fixture(kind: str, n: int, out_dir: Path) -> Fixture:
    """Generate an ``n``-frame ordered fixture of the given kind."""
    if kind not in FIXTURE_KINDS:
        raise ValueError(f"unknown fixture kind {kind!r}; expected one of {FIXTURE_KINDS}")
    if n < 2:
        raise ValueError("a fixture needs at least 2 frames to carry an order")
    if n > MAX_N[kind]:
        raise ValueError(f"{kind} fixtures support at most {MAX_N[kind]} frames (asked for {n})")

    out_dir = Path(out_dir).expanduser()
    out_dir.mkdir(parents=True, exist_ok=True)

    size = f"{FIXTURE_SIZE}x{FIXTURE_SIZE}"
    frame_paths: list[Path] = []
    labels: list[str] = []
    commands: list[str] = []

    for k in range(n):
        out_path = out_dir / f"{kind}_{n:02d}_{k:02d}.jpg"
        if kind == "color":
            name, hex_code = COLOR_PALETTE[k]
            cmd = _base_cmd(f"color=c={hex_code}:s={size}:d=1", out_path)
            label = name
        elif kind == "count":
            cmd = _base_cmd(f"color=c=black:s={size}:d=1", out_path, _count_boxes(k + 1))
            label = str(k + 1)
        else:  # motion
            cmd = _base_cmd(f"color=c=black:s={size}:d=1", out_path, _motion_box(k, n))
            label = str(k + 1)

        _run_ffmpeg(cmd)
        frame_paths.append(out_path)
        labels.append(label)
        commands.append(" ".join(cmd))

    return Fixture(kind=kind, n=n, frame_paths=frame_paths, labels=labels, ffmpeg_commands=commands)


def fixture_prompt(kind: str, n: int) -> str:
    """The question put to the model. Fixed text — changing it changes the benchmark."""
    common = (
        f"You are shown {n} images, in the order they were given to you. "
        "They are consecutive frames of a video. "
        "Answer with the ordered list only, comma-separated, no other words.\n"
    )
    if kind == "color":
        names = ", ".join(name for name, _ in COLOR_PALETTE)
        return common + (
            "Each image is a single solid colour. "
            f"List the colour of every image in order, first to last. "
            f"Use only these colour names: {names}."
        )
    if kind == "count":
        return common + (
            "Each image shows some white squares on a black background. "
            "List how many squares each image contains, in order, first to last."
        )
    return common + (
        "Each image shows one white square that moves horizontally between frames. "
        "Number the images 1 to N in the order given, then list those numbers sorted "
        "by the square's horizontal position, leftmost first."
    )
